  s_command.DataMode    		 = QSPI_DATA_4_LINES;    				// 4-wire data mode
  s_command.DummyCycles 		 = 6;                    				// Number of empty cycles
  s_command.NbData      		 = NumByteToRead;      			   	// Data length, the maximum cannot exceed the size of the flash chip
  s_command.Address     		 = ReadAddr;         					//Address to read W25Qxx
