  s_command.DummyCycles 		 = 6;                    				// Number of empty cycles
  s_command.Instruction 		 = W25Qxx_CMD_FastReadQuad_IO; 		// In 1-4-4 mode (1-line command, 4-line address, 4-line data), fast read command
  
